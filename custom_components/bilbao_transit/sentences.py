_FICHEROS = {"es": SENTENCES_ES, "en": SENTENCES_EN}

_CABECERA = (
    "# Frases de Bilbao Transit. Generado automáticamente: si lo editas, la\n"
    "# integración dejará de actualizarlo y respetará tus cambios.\n"
)


def _huella(cuerpo: str) -> str:
    """Hash corto del contenido, para saber si el usuario lo ha editado."""
    return hashlib.sha256(cuerpo.encode("utf-8")).hexdigest()[:16]


def _con_marca(cuerpo: str) -> str:
    """Fichero completo: huella, cabecera y frases."""
    return f"# huella: {_huella(cuerpo)}\n{_CABECERA}{cuerpo}"


def _cuerpo_sin_marca(contenido: str) -> tuple[str | None, str]:
    """Separa la huella declarada del cuerpo del fichero."""
    coincidencia = _MARCA.match(contenido)
    if not coincidencia:
        return None, contenido
    return coincidencia.group(1), contenido[coincidencia.end() :].replace(_CABECERA, "", 1)


async def async_ensure_sentences(hass: HomeAssistant) -> None:
    """Deja las frases en config/custom_sentences y las mantiene al día.

    - Si no existe, lo crea.
    - Si existe y **no** lo ha tocado el usuario (la huella cuadra, o es una
      versión anterior generada por la integración), lo actualiza.
    - Si el usuario lo editó, se respeta tal cual.
    """
    base = Path(hass.config.path("custom_sentences"))

    def _escribir() -> list[str]:
        escritos: list[str] = []
        for idioma, cuerpo in _FICHEROS.items():
            destino = base / idioma / "bilbao_transit.yaml"
            nuevo = _con_marca(cuerpo)
            if destino.exists():
                actual = destino.read_text(encoding="utf-8")
                if actual == nuevo:
                    continue
                declarada, resto = _cuerpo_sin_marca(actual)
                if declarada is not None:
                    editado = _huella(resto) != declarada
                else:
                    # sin huella: solo se puede tocar si es una versión nuestra
                    editado = actual.strip() not in _VERSIONS_ANTERIORES
                if editado:
                    _LOGGER.debug(
                        "Frases de %s editadas por el usuario, se respetan", idioma
                    )
                    continue
                _LOGGER.info("Actualizando frases de voz de %s", idioma)
            try:
                destino.parent.mkdir(parents=True, exist_ok=True)
                destino.write_text(nuevo, encoding="utf-8")
                escritos.append(str(destino))
            except OSError as err:  # permisos, disco lleno...
                _LOGGER.warning("No se pudieron escribir las frases de voz: %s", err)
        return escritos

    escritos = await hass.async_add_executor_job(_escribir)
    if escritos:
        _LOGGER.info(
            "Frases de voz listas en %s (reinicia Home Assistant para aplicarlas)",
            ", ".join(escritos),
        )
